#!/usr/bin/env python3
"""Export the locally built netfyr static family to WOFF2, with CSS and checks.

Reads TTF files supplied/generated by the user. No download or font installation.
Never overwrites an existing web export directory unless --force is specified.
"""
from __future__ import annotations
import argparse, hashlib, json, os, tempfile
from pathlib import Path
from fontTools.ttLib import TTFont
from fontTools.pens.recordingPen import RecordingPen
ROOT=Path(__file__).resolve().parents[1]
WEIGHTS=((300,'Light'),(400,'Regular'),(500,'Medium'),(600,'SemiBold'),(700,'Bold'),(800,'ExtraBold'),(900,'Black'))

def sha(p:Path)->str:
 return hashlib.sha256(p.read_bytes()).hexdigest()

def faces():
 for family in ('sans','mono'):
  for weight,label in WEIGHTS:
   for italic in (False,True):
    style=('Italic' if weight==400 else label+'Italic') if italic else label
    yield family,weight,italic,f'netfyr{family}-{style}'

def css_text()->str:
 blocks=['/* netfyr 0.507 — static faces, generated from the user\'s reviewed local TTF build. */']
 for family,weight,italic,name in faces():
  blocks.append(f'''@font-face {{
  font-family: "netfyr {family}";
  src: url("./{name}.woff2?v=0.507") format("woff2");
  font-weight: {weight};
  font-style: {"italic" if italic else "normal"};
  font-display: swap;
}}''')
 blocks.append('''.netfyr-sans { font-family: "netfyr sans", sans-serif; font-synthesis: none; }
.netfyr-mono { font-family: "netfyr mono", monospace; font-synthesis: none; }
.netfyr-cells { font-family: "netfyr mono", monospace; font-synthesis: none;
  line-height: 1.25; letter-spacing: 0; white-space: pre; }
''')
 return '\n\n'.join(blocks)

def main()->None:
 p=argparse.ArgumentParser(description=__doc__)
 p.add_argument('--build',required=True,type=Path,help='Local build output containing fonts/*.ttf')
 p.add_argument('--force',action='store_true')
 a=p.parse_args();build=a.build.resolve();out=build/'web'
 inputs=[build/'fonts'/f'{name}.ttf' for *_,name in faces()]
 missing=[x.name for x in inputs if not x.is_file()]
 if missing:p.error('Missing TTF inputs: '+', '.join(missing))
 targets=[out/f'{name}.woff2' for *_,name in faces()]+[out/'netfyr.css',out/'export-report.json']
 if not a.force and any(x.exists() for x in targets):p.error('Exports exist; choose another build or use --force.')
 report=json.loads((build/'build-report.json').read_text())
 repairs=json.loads((build/'repair-report.json').read_text())
 if report.get('version')!='0.507' or not report.get('baseline_reproduced') or not report.get('declared_repairs_verified') or not repairs['passed']:
  raise ValueError('Expected a validated reviewed revision')
 expected=report['hashes']
 if len(expected)!=28:raise ValueError('Incomplete reviewed family')
 out.mkdir(parents=True,exist_ok=True);reports=[]
 for family,weight,italic,name in faces():
  src=build/'fonts'/f'{name}.ttf';dst=out/f'{name}.woff2';digest=sha(src)
  if expected and digest!=expected.get(src.name):
   raise ValueError(f'{src.name}: differs from the validated 0.507 build')
  fd,tmpname=tempfile.mkstemp(dir=out,prefix='.'+name+'-',suffix='.tmp');os.close(fd);tmp=Path(tmpname)
  try:
   with TTFont(src,recalcTimestamp=False) as font:
    if round(font['head'].fontRevision,3)!=0.507:raise ValueError(f'{src.name}: unexpected revision')
    if font['OS/2'].usWeightClass!=weight:raise ValueError(f'{src.name}: weight mismatch')
    font.flavor='woff2';font.save(tmp)
   with TTFont(src) as before, TTFont(tmp) as after:
    if before.getBestCmap()!=after.getBestCmap():raise AssertionError(name+' cmap changed')
    if before['hmtx'].metrics!=after['hmtx'].metrics:raise AssertionError(name+' advances changed')
    if before.getGlyphOrder()!=after.getGlyphOrder():raise AssertionError(name+' glyph order changed')
    before_glyphs=before.getGlyphSet();after_glyphs=after.getGlyphSet()
    for glyph in before.getGlyphOrder():
     original=RecordingPen();converted=RecordingPen()
     before_glyphs[glyph].draw(original);after_glyphs[glyph].draw(converted)
     if original.value!=converted.value:raise AssertionError(name+' '+glyph+' outline changed')
    for table in ('name','OS/2','GSUB','GPOS','GDEF'):
     if table in before:
      if table not in after or before[table].compile(before)!=after[table].compile(after):
       raise AssertionError(name+' '+table+' changed')
   os.replace(tmp,dst)
  finally:tmp.unlink(missing_ok=True)
  reports.append({'source':src.name,'source_sha256':digest,'output':dst.name,'output_sha256':sha(dst),'bytes':dst.stat().st_size,'cmap_metrics_and_layout_preserved':True,'all_outlines_preserved':True})
 (out/'netfyr.css').write_text(css_text())
 (out/'export-report.json').write_text(json.dumps({'version':'0.507','files':reports,'scope':'FontTools WOFF2 conversion; all outlines, cmap, metrics and selected metadata/layout preserved. Not vendor acceptance.'},indent=2)+'\n')
 print(json.dumps({'files':len(reports),'output':str(out),'passed':True},indent=2))
if __name__=='__main__':main()
